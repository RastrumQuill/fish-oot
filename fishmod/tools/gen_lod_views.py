#!/usr/bin/env python3
"""Viewpoints for the LOD sweep (fishmod/scripts/lod_sweep.inc.c): where the camera can be around Lake Hylia, on a
grid over the water and its shores, each looked from in several directions. Above the water: from the shore and
shallows at Link's camera height, and from the surface where he'd swim; under it: from the bed, where he'd walk in
the Iron Boots. Each view carries its zone (fishmod/data/lake_hylia_zones.json), so the sweep can measure draw
distances per zone.

Made from the scene's collision (the extracted assets), so written to src/fishmod_data/ (not committed).

Usage: fishmod/tools/gen_lod_views.py [--spacing 450] [--yaws 4] [--pitches]
  --pitches: each view also looking further down and further up (the LOD tuning, lod_tune.inc.c: more angles)
"""
import argparse
import importlib.util
import math
import os
import random

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "src", "fishmod_data", "fishmod_lod_views.h")


def load_tool(name):
    spec = importlib.util.spec_from_file_location(name, os.path.join(ROOT, "fishmod", "tools", name + ".py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--spacing", type=int, default=450)
    ap.add_argument("--yaws", type=int, default=4)
    ap.add_argument("--pitches", action="store_true")
    args = ap.parse_args()
    gs = load_tool("gen_scatter")
    gw = gs.gw
    import json

    d = os.path.join(gw.SCENES, gs.SCENES["SCENE_LAKE_HYLIA"])
    vtx = gw.parse_vtx(gw.one(d, "*_VtxList.inc.c"))
    finder = gw.FloorFinder(gw.parse_floors(gw.one(d, "*_PolyList.inc.c"), vtx))
    boxes = gw.parse_waterboxes(gw.one(d, "*_WaterBoxes.inc.c"))
    zones = json.load(open(os.path.join(ROOT, "fishmod", "data", "lake_hylia_zones.json")))["zones"]
    rnd = random.Random(5)

    def surface_at(x, z):
        return next((b["y"] for b in boxes if b["xMin"] <= x <= b["xMin"] + b["xLen"] and
                     b["zMin"] <= z <= b["zMin"] + b["zLen"]), None)

    xs = [b["xMin"] for b in boxes] + [b["xMin"] + b["xLen"] for b in boxes]
    zs = [b["zMin"] for b in boxes] + [b["zMin"] + b["zLen"] for b in boxes]
    views = []
    for gz in range(min(zs), max(zs), args.spacing):
        for gx in range(min(xs), max(xs), args.spacing):
            x = gx + rnd.uniform(0, args.spacing)
            z = gz + rnd.uniform(0, args.spacing)
            surf = surface_at(x, z)
            if surf is None:
                continue
            top = finder.floor(int(x), int(z), surf + 800)
            if top is None or top > surf + 300:
                continue  # no floor, or a cliff or a roof
            zone = max(((gs.in_zone(zn, x, z), zn["id"]) for zn in zones), default=(0, 0))
            zone = zone[1] if zone[0] > 0 else 0
            eyes = []
            if top >= surf - 40:
                eyes.append((top + 110, -0.2, 0))  # standing on the shore or in the shallows
            else:
                eyes.append((surf + 90, -0.2, 0))  # swimming
                if surf - top > 150:
                    eyes.append((top + 70, 0.08, 1))  # walking the bed
            yaw0 = rnd.uniform(0, 2 * math.pi)
            if args.pitches:
                # also looking well down (at the bed through the water, or at the bed from a swim) and up
                eyes = [(ey, p, u) for ey, p0, u in eyes for p in ((p0 - 0.35, p0, p0 + 0.3) if u else
                                                                  (p0 - 0.3, p0, p0 + 0.2))]
            for ey, pitch, under in eyes:
                for k in range(args.yaws):
                    yaw = yaw0 + 2 * math.pi * k / args.yaws
                    at = (x + 300 * math.cos(pitch) * math.sin(yaw), ey + 300 * math.sin(pitch),
                          z + 300 * math.cos(pitch) * math.cos(yaw))
                    views.append((round(x), round(ey), round(z), round(at[0]), round(at[1]), round(at[2]), zone,
                                  under))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("// Generated by fishmod/tools/gen_lod_views.py from Lake Hylia's collision. Do not edit.\n")
        f.write(f"// {len(views)} views: eye, looked-at point, zone, under water\n")
        f.write("static FishmodLodView sLodViews[] = {\n")
        for v in views:
            f.write("    { { %d, %d, %d }, { %d, %d, %d }, %d, %d },\n" % v)
        f.write("};\n")
    n_under = sum(v[7] for v in views)
    print(f"{len(views)} views ({n_under} under water) in {len({v[6] for v in views})} zones -> {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
