#!/usr/bin/env python3
"""
Generates game data and wiki pages from fishmod/data/species.json.

  include/fishmod_species_data.h   species table + per-scene spawn tables (C)
  fishmod/wiki/README.md           wiki home
  fishmod/wiki/species/<id>.md     one page per species
  fishmod/wiki/baits.md            bait list

Usage: fishmod/tools/gen_species.py   (run from anywhere; paths are repo-relative)
"""

import json
import os

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))
DATA = os.path.join(ROOT, "fishmod", "data", "species.json")
HEADER = os.path.join(ROOT, "include", "fishmod_species_data.h")
WIKI = os.path.join(ROOT, "fishmod", "wiki")

BASES = {"bass": "FISHMOD_BASE_BASS", "loach": "FISHMOD_BASE_LOACH", "jabu": "FISHMOD_BASE_JABU", "small": "FISHMOD_BASE_SMALL"}
DEPTHS = {"surface": "FISHMOD_DEPTH_SURFACE", "mid": "FISHMOD_DEPTH_MID", "bottom": "FISHMOD_DEPTH_BOTTOM"}
TIMES = ["dawn", "day", "dusk", "night"]
BAITS = ["none", "bee_larva", "bug", "worm", "coral_earring", "fish"]
SCENE_IDS = {
    "KOKIRI_FOREST": "SCENE_KOKIRI_FOREST",
    "LAKE_HYLIA": "SCENE_LAKE_HYLIA",
    "ZORAS_RIVER": "SCENE_ZORAS_RIVER",
    "ZORAS_DOMAIN": "SCENE_ZORAS_DOMAIN",
    "ZORAS_FOUNTAIN": "SCENE_ZORAS_FOUNTAIN",
}
PARTS = ["head", "bodyFront", "bodyRear", "tail", "finDorsal", "finPectoral", "finBelly"]
RARITY_NAMES = {1: "Common", 2: "Uncommon", 3: "Rare", 4: "Very rare", 5: "Legendary"}


def weight(sp, length):
    return sp["weightCoef"] * length ** 3


def fmt_weight(lb):
    return f"{lb * 16:.0f} oz" if lb < 1.0 else f"{lb:.1f} lbs"


def gen_header(data):
    species = data["species"]
    out = []
    out.append("/* Generated by fishmod/tools/gen_species.py from fishmod/data/species.json. Do not edit. */")
    out.append("#ifndef FISHMOD_SPECIES_DATA_H")
    out.append("#define FISHMOD_SPECIES_DATA_H")
    out.append("")
    out.append('#include "fishmod.h"')
    out.append('#include "scene.h"')
    out.append('#include "array_count.h"')
    out.append("")
    out.append("const FishmodSpecies gFishmodSpecies[FISHMOD_SPECIES_MAX] = {")
    for sp in species:
        b = sp["behavior"]
        times = sum(1 << TIMES.index(t) for t in sp["activeTimes"])
        bait = ", ".join(f"{int(round(sp['bait'].get(k, 0.0) * 100))}" for k in BAITS)
        out.append(f"    /* FISHMOD_SPECIES_{sp['id']} */ {{")
        out.append(f'        "{sp["name"]}",')
        out.append(f"        {BASES[sp['base']]},")
        out.append(f"        {DEPTHS[sp['depth']]},")
        out.append(f"        {sp['rarity']}, {sp['price']}, 0x{times:X},")
        out.append(f"        {{ {', '.join(str(int(round(v * 100))) for v in sp['shape'])} }},")
        out.append(f"        {{ {', '.join(str(v) for v in sp['tint'])} }},")
        out.append(f"        {sp['length']['min']}, {sp['length']['typical']}, {sp['length']['max']},")
        out.append(f"        {sp['weightCoef'] * 1000000:.0f}, /* weight = coef * length^3 / 1000000 lbs */")
        out.append(
            f"        {{ {b['curiosity']}, {b['aggression']}, {b['wariness']}, {b['strength']}, {b['stamina']}, "
            f"{b['speed']}, {b['jumpiness']}, {b['nibbles']}, {b['biteWindow']} }},"
        )
        out.append(f"        {{ {bait} }},")
        look = sp.get("look", {})
        parts = look.get("parts", {})
        tints = []
        scales = []
        for part in PARTS:
            pp = parts.get(part, {})
            tints.append("{ " + ", ".join(str(v) for v in pp.get("tint", sp["tint"])) + " }")
            scales.append("{ " + ", ".join(str(int(round(v * 100))) for v in pp.get("scale", [1, 1, 1])) + " }")
        out.append(f"        {{ {', '.join(tints)} }},")
        out.append(f"        {{ {', '.join(scales)} }},")
        flags = []
        if look.get("whiskers"):
            flags.append("FISHMOD_LOOK_WHISKERS")
        out.append(f"        {' | '.join(flags) if flags else '0'},")
        out.append("    },")
    out.append("};")
    out.append("")
    # per-scene spawn tables
    scenes = {}
    for i, sp in enumerate(species):
        if sp["status"] != "in-game":
            continue
        for sc, w in sp["scenes"].items():
            scenes.setdefault(sc, []).append((sp["id"], w))
    for sc, entries in scenes.items():
        out.append(f"static const FishmodSpawnEntry sFishmodSpawns_{sc}[] = {{")
        for sid, w in entries:
            out.append(f"    {{ FISHMOD_SPECIES_{sid}, {w} }},")
        out.append("};")
    out.append("")
    out.append("const FishmodSceneSpawns gFishmodSceneSpawns[] = {")
    for sc, entries in scenes.items():
        out.append(f"    {{ {SCENE_IDS[sc]}, ARRAY_COUNT(sFishmodSpawns_{sc}), sFishmodSpawns_{sc} }},")
    out.append("};")
    out.append("")
    out.append("const s32 gFishmodSceneSpawnsCount = ARRAY_COUNT(gFishmodSceneSpawns);")
    out.append("")
    out.append("#endif")
    out.append("")

    enum = ["/* Generated by fishmod/tools/gen_species.py. Do not edit. */", "typedef enum FishmodSpeciesId {"]
    for i, sp in enumerate(species):
        enum.append(f"    /* {i:2} */ FISHMOD_SPECIES_{sp['id']},")
    enum.append("    /*    */ FISHMOD_SPECIES_MAX")
    enum.append("} FishmodSpeciesId;")
    return "\n".join(out), "\n".join(enum) + "\n"


def fmt_range(sp):
    l = sp["length"]
    return (
        f"{l['min']}–{l['max']} in (typically ~{l['typical']} in)",
        f"{fmt_weight(weight(sp, l['min']))} – {fmt_weight(weight(sp, l['max']))}",
    )


def bar(v):
    n = round(v / 10)
    return "█" * n + "░" * (10 - n) + f" {v}"


def gen_species_page(sp, data):
    length, weights = fmt_range(sp)
    b = sp["behavior"]
    img = f"../img/{sp['id'].lower()}.jpg"
    img34 = f"../img/{sp['id'].lower()}_34.jpg"
    have_img = os.path.exists(os.path.join(WIKI, "img", sp["id"].lower() + ".jpg"))
    have_img34 = os.path.exists(os.path.join(WIKI, "img", sp["id"].lower() + "_34.jpg"))
    lines = [f"# {sp['name']}", ""]
    status = "In game" if sp["status"] == "in-game" else "Planned (not in the game yet)"
    lines.append(f"*{RARITY_NAMES[sp['rarity']]} · from {sp['origin']} · {status}*")
    lines.append("")
    if have_img and have_img34:
        lines.append(f'<img src="{img}" width="49%"> <img src="{img34}" width="49%">')
        lines.append("")
        lines.append(f"*In-game renders at a typical size ({sp['length']['typical']} in), captured in ares.*")
    elif have_img:
        lines.append(f"![{sp['name']}]({img})")
    else:
        lines.append("*(render pending: this fish is not in the game yet)*")
    lines.append("")
    lines.append(f"> {sp['flavor']}")
    lines.append("")
    lines.append("## Stats")
    lines.append("")
    lines.append("| | |")
    lines.append("|---|---|")
    lines.append(f"| Length | {length} |")
    lines.append(f"| Weight | {weights} |")
    lines.append(f"| Rarity | {RARITY_NAMES[sp['rarity']]} ({sp['rarity']}/5) |")
    lines.append(f"| Sell price | {sp['price']} rupees (more for bigger fish) |")
    lines.append(f"| Depth | {sp['depth']} |")
    lines.append(f"| Most active | {', '.join(sp['activeTimes'])} |")
    where = ", ".join(
        f"{data['scenes'][s]['name']}" + ("" if data["scenes"][s]["status"] == "in-game" else " (planned)")
        for s in sp["scenes"]
    )
    lines.append(f"| Found in | {where} |")
    lines.append("")
    lines.append("## Behavior")
    lines.append("")
    lines.append("```")
    for k in ["curiosity", "aggression", "wariness", "strength", "stamina", "speed", "jumpiness"]:
        lines.append(f"{k:<11}{bar(b[k])}")
    lines.append(f"{'nibbles':<11}{b['nibbles']} before the real bite")
    lines.append(f"{'bite window':<11}{b['biteWindow']} frames ({b['biteWindow'] / 20:.2f} s) to set the hook")
    lines.append("```")
    lines.append("")
    lines.append("## Bait")
    lines.append("")
    lines.append("| Bait | Interest |")
    lines.append("|---|---|")
    names = {bt["id"]: bt["name"] for bt in data["baits"]}
    for k, v in sp["bait"].items():
        lines.append(f"| {names.get(k, k)} | {'none' if v == 0 else f'×{v:.1f}'} |")
    lines.append("")
    lines.append("## Tips")
    lines.append("")
    lines.append(sp["tips"])
    lines.append("")
    lines.append("[← All fish](../README.md)")
    lines.append("")
    return "\n".join(lines)


def gen_index(data):
    lines = ["# fish-oot wiki", ""]
    lines.append("Twilight Princess-style overworld fishing for Ocarina of Time (N64). "
                 "Pages are generated from [`fishmod/data/species.json`](../data/species.json); "
                 "behavior and sizes match the game.")
    lines.append("")
    lines.append("- [How the fish are modeled](modeling.md)")
    lines.append("- [Research notes and sources](research.md)")
    lines.append("- [Bait](baits.md)")
    lines.append("")
    lines.append("## Fish")
    lines.append("")
    if os.path.exists(os.path.join(WIKI, "img", "lineup.jpg")):
        lines.append('<img src="img/lineup.jpg" width="60%">')
        lines.append("")
        lines.append("*Kokiri Forest fish at typical size, to scale. Top to bottom: Hyrule Minnow, Greengill, "
                     "Hylian Loach, Hyrule Bass, Sanke Carp, Ordon Catfish.*")
        lines.append("")
    lines.append("| | Fish | Rarity | Length | Where | Status |")
    lines.append("|---|---|---|---|---|---|")
    for sp in data["species"]:
        img = os.path.join(WIKI, "img", sp["id"].lower() + ".jpg")
        thumb = f"<img src=\"img/{sp['id'].lower()}.jpg\" width=\"120\">" if os.path.exists(img) else ""
        where = ", ".join(data["scenes"][s]["name"] for s in sp["scenes"])
        status = "in game" if sp["status"] == "in-game" else "planned"
        lines.append(
            f"| {thumb} | [{sp['name']}](species/{sp['id'].lower()}.md) | {RARITY_NAMES[sp['rarity']]} | "
            f"{sp['length']['min']}–{sp['length']['max']} in | {where} | {status} |"
        )
    lines.append("")
    return "\n".join(lines)


def gen_baits(data):
    lines = ["# Bait", "", "| Bait | Where to get it | Notes |", "|---|---|---|"]
    for bt in data["baits"]:
        lines.append(f"| {bt['name']} | {bt['source']} | {bt['notes']} |")
    lines.append("")
    lines.append("## Which fish like what")
    lines.append("")
    ids = [bt["id"] for bt in data["baits"]]
    lines.append("| Fish | " + " | ".join(bt["name"] for bt in data["baits"]) + " |")
    lines.append("|---|" + "---|" * len(ids))
    for sp in data["species"]:
        row = []
        for k in ids:
            v = sp["bait"].get(k)
            row.append("–" if not v else f"×{v:.1f}")
        lines.append(f"| [{sp['name']}](species/{sp['id'].lower()}.md) | " + " | ".join(row) + " |")
    lines.append("")
    lines.append("[← Wiki home](README.md)")
    lines.append("")
    return "\n".join(lines)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)


def main():
    with open(DATA) as f:
        data = json.load(f)

    header, enum = gen_header(data)
    write(HEADER, header)
    write(os.path.join(ROOT, "include", "fishmod_species_ids.h"), enum)

    for sp in data["species"]:
        write(os.path.join(WIKI, "species", sp["id"].lower() + ".md"), gen_species_page(sp, data))
    write(os.path.join(WIKI, "README.md"), gen_index(data))
    write(os.path.join(WIKI, "baits.md"), gen_baits(data))
    print(f"generated {len(data['species'])} species")


if __name__ == "__main__":
    main()
