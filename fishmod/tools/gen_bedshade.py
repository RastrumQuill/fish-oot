#!/usr/bin/env python3
"""Shading for Lake Hylia's bed under the full lake: darker under dense weed beds and lily pads (their shade) and
deeper down, from the props' placement (gen_scatter.py) and the depth.

The lake's ground is lit by the scene's lights, so its vertices carry normals, not colours. The N64's F3DEX2 lights a
vertex with its normal as stored (it isn't normalised again), so a shorter normal takes less of the sun: the shading
is made by shortening the normals of the vertices under the water. Only the sunlight changes; the ambient light,
the day and night colours and the underwater lights all still apply. The drained lake (adult Link before the Water
Temple) is left as it is: the game only applies this with the lake full.

The ground has few vertices (about 340 under the water), so this is broad shading, not detail.

Made from the scene's own vertices (the extracted assets), so written to src/fishmod_data/ (not committed).

Usage: fishmod/tools/gen_bedshade.py [--png preview.png]
"""
import argparse
import glob
import math
import os
import re

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))
SCENE = os.path.join(ROOT, "extracted", "ntsc-1.2", "assets", "scenes", "overworld", "spot06")
OUT = os.path.join(ROOT, "src", "fishmod_data", "fishmod_bedshade.h")
SURFACE = -1313  # the full lake
# how much shade each kind casts on the bed around it
SHADE = {"bush_weed": 1.0, "broadleaf": 1.0, "big_pondweed": 1.2, "kelp_frond": 1.2, "tall_weed": 1.0,
         "ribbon_weed": 0.7, "grass_tuft": 0.4, "fan_weed": 0.8, "vine_strand": 0.6, "lily_pad": 1.6,
         "spatterdock": 1.2, "float_leaves": 0.8, "pond_reed": 0.5, "reed_clump": 0.6, "cattails": 0.6}
SIGMA = 220.0     # the shade's spread
DENSE = 6.0       # this much shade nearby is a dense bed
BED_DARK = 0.45   # how much of the sunlight a dense bed takes
DEPTH_DARK = 0.3  # and the deep water, from DEPTH0 down to DEPTH1 below the surface
DEPTH0, DEPTH1 = 250.0, 1100.0
FADE = 80.0       # up to this far under the surface, less of it (no seam at the waterline)


def load_tool(name):
    import importlib.util

    spec = importlib.util.spec_from_file_location(name, os.path.join(ROOT, "fishmod", "tools", name + ".py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


VTX = re.compile(r"VTX\(\s*(-?\d+),\s*(-?\d+),\s*(-?\d+),\s*(-?\w+),\s*(-?\w+),\s*(-?\w+),\s*(-?\w+),\s*(-?\w+),"
                 r"\s*(-?\w+)\),\s*// (\d+)")


def s8(v):
    v = int(v, 0)
    return v - 256 if v >= 128 else v


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--png")
    args = ap.parse_args()
    gs = load_tool("gen_scatter")
    props = gs.place("SCENE_LAKE_HYLIA")
    shade_pts = [(p["x"], p["z"], SHADE[p["kind"]] * p["scale"]) for p in props if p["kind"] in SHADE]

    out = []
    for path in sorted(glob.glob(os.path.join(SCENE, "*_Vtx_fused_.inc.c"))):
        base = int(re.search(r"_(03[0-9A-F]{6})_Vtx", path).group(1), 16) & 0xFFFFFF
        for m in VTX.finditer(open(path).read()):
            x, y, z = int(m.group(1)), int(m.group(2)), int(m.group(3))
            depth = SURFACE - y
            if depth <= 0:
                continue
            n = [s8(m.group(i)) for i in (6, 7, 8)]
            near = sum(w * math.exp(-((x - px) ** 2 + (z - pz) ** 2) / (2 * SIGMA ** 2)) for px, pz, w in shade_pts
                       if abs(x - px) < 3 * SIGMA and abs(z - pz) < 3 * SIGMA)
            dense = 1.0 - math.exp(-near / DENSE)
            deep = min(max((depth - DEPTH0) / (DEPTH1 - DEPTH0), 0.0), 1.0)
            f = (1.0 - BED_DARK * dense) * (1.0 - DEPTH_DARK * deep)
            f = 1.0 - (1.0 - f) * min(depth / FADE, 1.0)
            nn = [max(-128, min(127, round(c * f))) for c in n]
            if nn != n:
                out.append((base + int(m.group(10)) * 16 + 12, nn, (x, z, f)))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("// Generated by fishmod/tools/gen_bedshade.py from Lake Hylia's room. Do not edit.\n")
        f.write("// The bed's vertices under the full lake: where their normals are in the room, and the shorter\n")
        f.write("// normals (less of the sun under dense weed and in deep water).\n")
        f.write(f"#define FISHMOD_BEDSHADE_COUNT {len(out)}\n")
        f.write("static const FishmodBedShade sFishmodBedShade[] = {\n")
        for off, nn, _ in out:
            f.write("    { 0x%06X, { %d, %d, %d } },\n" % (off, *nn))
        f.write("};\n")
    fs = [o[2][2] for o in out]
    print(f"{len(out)} vertices shaded (sunlight x{min(fs):.2f} to x{max(fs):.2f}) -> {os.path.relpath(OUT, ROOT)}")
    if args.png:
        from PIL import Image, ImageDraw

        img = Image.new("RGB", (700, 640), (20, 30, 40))
        d = ImageDraw.Draw(img)
        for px, pz, w in shade_pts:
            X, Y = (px + 4800) / 10, (pz - 3300) / 10
            d.point((X, Y), fill=(40, 90, 40))
        for _, _, (x, z, fct) in out:
            X, Y = (x + 4800) / 10, (z - 3300) / 10
            v = int(255 * fct)
            d.ellipse((X - 4, Y - 4, X + 4, Y + 4), fill=(v, v, v))
        img.save(args.png)


if __name__ == "__main__":
    main()
