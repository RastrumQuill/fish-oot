#!/usr/bin/env python3
"""Generates the bait bottle icons (32x32 RGBA32, like the vanilla bottle icons) from the vanilla empty bottle:
larva bottles with 3, 2 and 1 grubs in them. Writes src/code/fishmod_bait_icons.inc.c and preview PNGs in
fishmod/art/. Needs the extracted assets (make setup) and Pillow."""
import os
from PIL import Image, ImageDraw

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))
BOTTLE = os.path.join(ROOT, "extracted", "ntsc-1.2", "assets", "textures", "icon_item_static",
                      "gItemIconBottleEmptyTex.rgba32.png")
OUT_C = os.path.join(ROOT, "src", "code", "fishmod_bait_icons.inc.c")
OUT_ART = os.path.join(ROOT, "fishmod", "art")

# grub spots inside the bottle's body (bottom first), as (x, y) of the grub's middle
SPOTS = [(14, 25), (19, 22), (13, 19)]
GRUB = (240, 226, 170)
GRUB_DARK = (186, 160, 96)


def grub(img, cx, cy, flip):
    # a curled grub: an arc of overlapping round segments, darker lines between them
    d = ImageDraw.Draw(img)
    segs = [(-3, 1), (-1, -1), (1, -1), (3, 1)]
    if flip:
        segs = [(-x, y) for x, y in segs]
    for i, (dx, dy) in enumerate(segs):
        r = 2 if i in (1, 2) else 1.6
        d.ellipse([cx + dx - r, cy + dy - r, cx + dx + r, cy + dy + r], fill=GRUB + (255,))
    for dx, dy in segs[1:]:
        img.putpixel((cx + dx - (1 if not flip else -1), cy + dy), GRUB_DARK + (255,))
    img.putpixel((cx + segs[0][0], cy + segs[0][1]), (120, 90, 50, 255))  # head


def icon(count):
    base = Image.open(BOTTLE).convert("RGBA")
    layer = Image.new("RGBA", base.size, (0, 0, 0, 0))
    for i in range(count):
        grub(layer, SPOTS[i][0], SPOTS[i][1], i % 2 == 1)
    # seen through the glass: a little of the bottle's darkness over the grubs
    layer.putalpha(layer.getchannel("A").point(lambda a: a * 215 // 255))
    return Image.alpha_composite(base, layer)


def main():
    os.makedirs(OUT_ART, exist_ok=True)
    lines = ["// Generated by fishmod/tools/gen_bait_icons.py: bait bottle icons, 32x32 RGBA32. Edit the script.", ""]
    for count in (3, 2, 1):
        img = icon(count)
        img.save(os.path.join(OUT_ART, f"bottle_larva_{count}.png"))
        img.resize((128, 128), Image.NEAREST).save(os.path.join(OUT_ART, f"bottle_larva_{count}_x4.png"))
        words = []
        px = list(img.get_flattened_data()) if hasattr(img, "get_flattened_data") else list(img.getdata())
        for i in range(0, len(px), 2):
            a, b = px[i], px[i + 1]
            words.append("0x%02X%02X%02X%02X%02X%02X%02X%02X" % (a + b))
        lines.append(f"u64 gFishmodBottleLarva{count}Tex[32 * 32 / 2] = {{")
        for i in range(0, len(words), 4):
            lines.append("    " + ", ".join(words[i:i + 4]) + ",")
        lines.append("};")
        lines.append("")
    with open(OUT_C, "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
