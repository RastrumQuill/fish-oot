#!/usr/bin/env python3
"""The animation check's case table (fishmod/docs/anim-verify.md): every one of Link's animations, read from the
game's own list of them (assets/objects/gameplay_keep/player_anim_headers.c), so none is missed and a new one is
picked up. Each animation's frame count is read from its header in the ROM at run time; the harness steps through
every frame, the half frames between them, and the variant axes (age, equipment, face, lights, camera angles).

Writes src/fishmod_data/fishmod_animcheck_cases.h (made at build time, not committed: it lists the game's assets).

Usage: fishmod/tools/gen_animcheck_cases.py [--check]   (--check: print the count only)
"""
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = os.path.join(ROOT, "assets", "objects", "gameplay_keep", "player_anim_headers.c")
OUT = os.path.join(ROOT, "src", "fishmod_data", "fishmod_animcheck_cases.h")


# other actors' objects the check can pose (fishmod/scripts/animcheck_<object>.inc.c): object, skeleton
ACTOR_OBJECTS = [("object_tite", "object_tite_Skel_003A20")]


def actor_tables():
    """for each object listed: its skeleton's animations (those with its joint count), as a table header"""
    import sys as _sys
    _sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import skel_survey as sv
    for obj_name, skel_name in ACTOR_OBJECTS:
        d = os.path.join(ROOT, "extracted", "ntsc-1.2", "assets", "objects", obj_name)
        obj = sv.parse_object(d)
        if obj is None:
            continue
        sk = [x for x in obj["skels"] if x["name"] == skel_name]
        if not sk:
            sys.exit("no skeleton %s in %s" % (skel_name, obj_name))
        n = len(sk[0]["limbs"])
        anims = [a["name"] for a in obj["anims"] if len(a["joints"]) == n + 1]
        out = os.path.join(ROOT, "src", "fishmod_data", "fishmod_animcheck_%s.h" % obj_name)
        lines = ["// Generated by fishmod/tools/gen_animcheck_cases.py: %s's animations for %s. Do not edit." % (obj_name, skel_name),
                 '#include "assets/objects/%s/%s.h"' % (obj_name, obj_name),
                 "#define FISHMOD_ANIMCHECK_ACTOR_ANIMS %d" % len(anims),
                 "#define FISHMOD_ANIMCHECK_ACTOR_LIMBS %d" % n,
                 "static AnimationHeader* const sAnimCheckActorAnims[FISHMOD_ANIMCHECK_ACTOR_ANIMS] = {"]
        lines += ["    &%s," % a for a in anims]
        lines += ["};", "#define FISHMOD_ANIMCHECK_ACTOR_SKEL %s" % skel_name, ""]
        open(out, "w").write("\n".join(lines))
        print("wrote %s: %d animations" % (os.path.relpath(out, ROOT), len(anims)))


def main():
    actor_tables()
    names = re.findall(r"^LinkAnimationHeader (\w+) =", open(SRC).read(), re.M)
    if not names:
        sys.exit("no animations found in %s" % SRC)
    if "--check" in sys.argv:
        print("%d Link animations" % len(names))
        return
    lines = ["// Generated by fishmod/tools/gen_animcheck_cases.py from %s. Do not edit." % os.path.relpath(SRC, ROOT),
             "// Every one of Link's animations, for the animation check (fishmod/docs/anim-verify.md).",
             '#include "assets/objects/gameplay_keep/player_anim_headers.h"',
             "#define FISHMOD_ANIMCHECK_LINK_ANIMS %d" % len(names),
             "static LinkAnimationHeader* const sAnimCheckLinkAnims[FISHMOD_ANIMCHECK_LINK_ANIMS] = {"]
    lines += ["    &%s," % n for n in names]
    lines += ["};", ""]  # (the names: animcheck_compare.py reads this file's list, in the same order)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write("\n".join(lines))
    print("wrote %s: %d animations" % (os.path.relpath(OUT, ROOT), len(names)))


if __name__ == "__main__":
    main()
