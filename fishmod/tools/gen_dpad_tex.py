#!/usr/bin/env python3
"""The HUD's D-pad texture (our own art): a cross shaded as the C buttons are, a flat face with a bevelled rim lit
from the upper left, a dished middle and small arrows pressed into its arms (under the items). IA8, drawn tinted by the primitive colour.

Writes src/fishmod_data/fishmod_dpad_tex.inc.c (and --png PATH, a preview).
Usage: fishmod/tools/gen_dpad_tex.py [--png PATH]
"""
import argparse
import os

import numpy as np
from PIL import Image
from scipy import ndimage

SIZE = 48     # texels
ARM = 16      # arm width (texels)
SUPER = 8
FACE = 170    # the flat face's intensity (the C buttons' own)
BEVEL = 2.2   # rim width (texels)

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))


def render():
    n = SIZE * SUPER
    c = (n - 1) / 2
    y, x = np.mgrid[0:n, 0:n].astype(float)
    half = ARM * SUPER / 2
    r = 2.5 * SUPER  # rounded arm ends
    inside = ((np.abs(x - c) <= half) | (np.abs(y - c) <= half)) & (np.abs(x - c) <= n / 2 - 1) & (np.abs(y - c) <= n / 2 - 1)
    # round the four arm tips' corners
    for sx in (-1, 1):
        for sy in (-1, 1):
            for (ax, ay) in ((half - r, n / 2 - 1 - r), (n / 2 - 1 - r, half - r)):
                cx, cy = c + sx * ax, c + sy * ay
                corner = (sx * (x - cx) > 0) & (sy * (y - cy) > 0)
                inside &= ~(corner & ((x - cx) ** 2 + (y - cy) ** 2 > r * r))
    dist = ndimage.distance_transform_edt(inside) / SUPER  # texels in from the edge
    h = np.clip(dist / BEVEL, 0, 1)
    h = np.sin(h * np.pi / 2)  # a rounded rim
    # the dished middle
    rr = np.hypot(x - c, y - c) / SUPER
    h -= 0.35 * np.clip(1 - rr / 6.5, 0, 1) ** 2
    dent = np.zeros_like(inside)
    # an arrow pressed into each arm, under its item (pointing out; seen when the button is empty)
    for ang in range(4):
        u = (x - c) / SUPER
        v = (y - c) / SUPER
        for _ in range(ang):
            u, v = v, -u
        tri = (v < -13.0) & (v > -20.5) & (np.abs(u) < (v + 20.5) * 0.75)
        h -= 0.45 * tri
        dent |= tri
    h = ndimage.gaussian_filter(h, SUPER * 0.35)
    gy, gx = np.gradient(h * SUPER)
    light = np.array([-1.0, -1.0]) / np.sqrt(2)  # from the upper left
    shade = (gx * light[0] + gy * light[1])
    inten = np.clip(FACE + 520 * -shade, 30, 255)
    inten = np.where(ndimage.binary_dilation(dent, iterations=SUPER // 2), inten * 0.82, inten)  # (the dents a little darker)
    # downsample: alpha is coverage, intensity the covered samples' mean
    a = inside.reshape(SIZE, SUPER, SIZE, SUPER).mean(axis=(1, 3))
    s = (inten * inside).reshape(SIZE, SUPER, SIZE, SUPER).sum(axis=(1, 3))
    cnt = inside.reshape(SIZE, SUPER, SIZE, SUPER).sum(axis=(1, 3))
    i = np.where(cnt > 0, s / np.maximum(cnt, 1), 0)
    return np.round(i).astype(np.uint8), np.round(a * 255).astype(np.uint8)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--png")
    args = ap.parse_args()
    i, a = render()
    if args.png:
        Image.fromarray(np.stack([i, a], -1), "LA").save(args.png)
    out = os.path.join(ROOT, "src", "fishmod_data", "fishmod_dpad_tex.inc.c")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    data = [(int(iv) & 0xF0) | (int(av) >> 4) for iv, av in zip(i.reshape(-1), a.reshape(-1))]
    lines = ["// Generated by fishmod/tools/gen_dpad_tex.py. Do not edit.",
             f"// The HUD's D-pad: {SIZE} x {SIZE} IA8.",
             f"static u64 sFishmodDpadTex[{SIZE * SIZE // 8}] = {{"]
    words = [int.from_bytes(bytes(data[k:k + 8]), "big") for k in range(0, len(data), 8)]
    for k in range(0, len(words), 4):
        lines.append("    " + ", ".join(f"0x{w:016X}" for w in words[k:k + 4]) + ",")
    lines.append("};")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
