#!/usr/bin/env python3
"""Build profiles (fishmod/data/profiles.json): the settings for the kind of machine a ROM is made for.

    from build_profile import load
    p = load()              # FISHMOD_PROFILE from the environment (the build sets it), else "emu"
    p = load("hw")

Run it to write the C header for a profile:  build_profile.py NAME [--c src/fishmod_data/fishmod_profile.h]
"""
import argparse
import json
import os

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
DATA = os.path.join(ROOT, "fishmod", "data", "profiles.json")
HEADER = os.path.join(ROOT, "src", "fishmod_data", "fishmod_profile.h")
DEFAULT = "emu"


def names():
    return [k for k in json.load(open(DATA)) if not k.startswith("_")]


def load(name=None):
    name = name or os.environ.get("FISHMOD_PROFILE") or DEFAULT
    profiles = json.load(open(DATA))
    if name not in profiles or name.startswith("_"):
        raise SystemExit(f"profiles.json: no profile {name!r} (have: {', '.join(names())})")
    p = dict(profiles[name])
    p["name"] = name
    return p


def header(p):
    d = p["draw"]
    lines = [
        f"// Generated by fishmod/tools/build_profile.py from fishmod/data/profiles.json (profile {p['name']}). Do not edit.",
        "#ifndef FISHMOD_PROFILE_H",
        "#define FISHMOD_PROFILE_H",
        f"#define FISHMOD_PROFILE_HW {1 if p['name'] == 'hw' else 0} // made for the original hardware",
        f"#define FISHMOD_PROFILE_THINNED {1 if p['thinning'] else 0}",
        f"#define FISHMOD_PROFILE_PROP_BUDGET {int(p['prop_budget'])}",
        f"#define FISHMOD_PROFILE_XLU_MAX {int(p['xlu_max'])}",
        f"#define FISHMOD_PROFILE_DIST_SMALL {float(d['small'])}f",
        f"#define FISHMOD_PROFILE_DIST_MID {float(d['mid'])}f",
        f"#define FISHMOD_PROFILE_DIST_FAR {float(d['far'])}f",
        f"#define FISHMOD_PROFILE_DIST_UNDER_FOG {float(d['under_fog'])}f",
        "#endif",
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("name", nargs="?")
    ap.add_argument("--c", default=HEADER, help="where to write the C header")
    ap.add_argument("--get", help="print one setting (e.g. f3dex3, suffix) and exit")
    args = ap.parse_args()
    p = load(args.name)
    if args.get:
        v = p[args.get]
        print(int(v) if isinstance(v, bool) else v)
        return
    text = header(p)
    os.makedirs(os.path.dirname(args.c), exist_ok=True)
    if not os.path.exists(args.c) or open(args.c).read() != text:  # (unchanged: no rebuild)
        with open(args.c, "w") as f:
            f.write(text)
    print(f"profile {p['name']} -> {os.path.relpath(args.c, ROOT)}")


if __name__ == "__main__":
    main()
