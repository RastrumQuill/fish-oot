#!/usr/bin/env python3
"""Writes assets/audio/sequences/seq_110.seq: the fish-on music (NA_BGM_FISHMOD_FIGHT).

An 8-bar loop in E minor at 160 BPM using the field soundfont (Soundfont 3), the instruments the field enemy
theme uses: a fast repeating 16th-note bass ostinato (like Twilight Princess's reeling music), held low roots,
a sustained tension line on top and a soft 16th-note pulse on the drums. Tense, not combat.
Edit the tables below and rerun to change it.
"""
import os

TICKS_PER_BEAT = 48
BAR = TICKS_PER_BEAT * 4
SIXTEENTH = TICKS_PER_BEAT // 4

NOTE_NAMES = ["A", "BF", "B", "C", "DF", "D", "EF", "E", "F", "GF", "G", "AF"]


def pitch(name):
    """'E2' -> 'PITCH_E2' (the aseq names count octaves from C, pitch values from A0)."""
    return "PITCH_" + name


def semis(name):
    base = {"C": 3, "DF": 4, "D": 5, "EF": 6, "E": 7, "F": 8, "GF": 9, "G": 10, "AF": 11, "A": 0, "BF": 1, "B": 2}
    letters = name.rstrip("0123456789")
    octave = int(name[len(letters):])
    value = base[letters] + 12 * octave - (12 if base[letters] >= 3 else 0)
    return value


def name_of(value):
    # inverse of semis()
    octave = value // 12
    idx = value % 12
    if idx >= 3:
        octave += 1
    return NOTE_NAMES[idx] + str(octave)


ROOTS = ["E2", "E2", "C2", "D2", "E2", "E2", "F2", "B1"]
# bass ostinato per bar, in semitones above the root
BASS_PATTERN = [0, 0, 12, 0, 0, 0, 7, 0, 0, 0, 12, 0, 10, 0, 7, 0]
# tension line: (note, bars)
PAD = [("B3", 2), ("C4", 1), ("A3", 1), ("B3", 2), ("C4", 1), ("EF4", 1)]


def bass_layer():
    out = []
    for root in ROOTS:
        r = semis(root)
        for i, step in enumerate(BASS_PATTERN):
            vel = 104 if i % 4 == 0 else 76
            out.append(f"    notedvg     {pitch(name_of(r + step))}, {SIXTEENTH}, {vel}, 96")
    return out


def root_layer():
    return [f"    notedv      {pitch(root)}, {BAR}, 92" for root in ROOTS]


def pad_layer():
    return [f"    notedv      {pitch(note)}, {BAR * bars}, 72" for note, bars in PAD]


def drum_layer():
    out = []
    for _ in ROOTS:
        for i in range(16):
            note = "E2" if i % 2 == 0 else "F2"
            vel = 70 if i % 4 == 0 else 46
            out.append(f"    notedvg     {pitch(note)}, {SIXTEENTH}, {vel}, 43")
    return out


CHANNELS = [
    # name, layer, instrument, volume, pan, reverb
    ("BASS", bass_layer, "SF3_INST_11", 115, 64, 8),
    ("ROOT", root_layer, "SF3_INST_12", 90, 56, 16),
    ("PAD", pad_layer, "SF3_INST_7", 72, 40, 64),
    ("DRUMS", drum_layer, "FONTANY_INSTR_DRUM", 80, 84, 16),
]


def main():
    loop = BAR * len(ROOTS)
    lines = [
        "// Generated by fishmod/tools/gen_fight_seq.py: the fish-on music. Edit the script, not this file.",
        '#include "aseq.h"',
        '#include "Soundfont_3.h"',
        "",
        ".startseq Sequence_110",
        "",
        ".sequence FIGHT_SEQ",
        "    mutebhv     0x20",
        "    mutescale   50",
        f"    initchan    0b{'1' * len(CHANNELS)}",
        "    vol         72",
        "    tempo       160",
        "FIGHT_SEQ_LOOP:",
    ]
    for i, (name, _, _, _, _, _) in enumerate(CHANNELS):
        lines.append(f"    ldchan      {i}, FIGHT_CHAN_{name}")
    lines += [f"    delay       {loop}", "    jump        FIGHT_SEQ_LOOP", ""]
    for name, layer, instr, vol, pan, reverb in CHANNELS:
        lines += [
            f".channel FIGHT_CHAN_{name}",
            "    noshort",
            f"    ldlayer     0, FIGHT_LAYER_{name}",
            f"    vol         {vol}",
            f"    pan         {pan}",
            f"    reverb      {reverb}",
            f"    instr       {instr}",
            f"    delay       {loop}",
            "    end",
            "",
        ]
    for name, layer, _, _, _, _ in CHANNELS:
        lines += [f".layer FIGHT_LAYER_{name}"] + layer() + ["    end", ""]
    lines += [".endseq Sequence_110", ""]

    root = os.path.join(os.path.dirname(__file__), "..", "..")
    with open(os.path.join(root, "assets", "audio", "sequences", "seq_110.seq"), "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
